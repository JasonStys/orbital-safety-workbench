"""Generate/check exact-line code and file inventories by Jason Stys.

Functions: source_files, inventory, main. Variables: ROOT, exclusions and source suffixes.
Headers reference this index instead of fragile duplicated line numbers. Index: docs/CODE_INDEX.md.
"""

import argparse
import ast
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SKIP = {
    ".git",
    ".venv",
    ".runtime",
    "node_modules",
    "__pycache__",
    ".pytest_cache",
    ".hypothesis",
    ".mypy_cache",
    ".ruff_cache",
    "dist",
    "build",
    "test-results",
    "playwright-report",
}
SOURCE_SUFFIXES = {".py", ".ts", ".css", ".html", ".sql"}


def source_files() -> list[Path]:
    """Walk only small authored trees; prune dependencies and generated/private outputs."""
    result = []
    for directory, children, files in ROOT.walk():
        children[:] = sorted(name for name in children if name not in SKIP)
        result.extend(
            directory / name
            for name in sorted(files)
            if name != ".coverage" and not name.endswith(".spec")
        )
    return sorted(result)


def inventory() -> tuple[str, str]:
    """Extract Python AST definitions/stores/parameters and lexical web/SQL declarations."""
    code = [
        "# Exact-line code index",
        "",
        "Generated by `python tools/verify_repo.py --write`. CI rejects stale output.",
        "Headers describe responsibilities; docstrings describe contracts and variable roles.",
        "Python entries include assigned names and arguments; web entries list declarations/fields/IDs/selectors.",
        "Line numbers refer to formatted source, not this generated document.",
        "",
    ]
    catalog = [
        "# File catalog",
        "",
        "Every tracked-intent file; dependencies/private outputs are excluded.",
        "",
    ]
    for path in source_files():
        relative = path.relative_to(ROOT).as_posix()
        if relative in {"docs/CODE_INDEX.md", "docs/FILE_CATALOG.md"}:
            continue
        content = (
            "Binary screenshot asset from local application validation"
            if path.suffix in {".jpg", ".png"}
            else path.read_text(encoding="utf-8")
        )
        summary = content.splitlines()[0][:150] if content.splitlines() else "Empty file"
        catalog.append(f"- `{relative}` — {summary.replace('`', '')}")
        if path.suffix not in SOURCE_SUFFIXES:
            continue
        if "Jason Stys" not in "\n".join(content.splitlines()[:8]):
            raise ValueError(f"Missing creator/responsibility header: {relative}")
        entries = set()
        if path.suffix == ".py":
            tree = ast.parse(content)
            for node in ast.walk(tree):
                if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                    if not ast.get_docstring(node):
                        raise ValueError(f"Missing definition contract: {relative}:{node.lineno}")
                    entries.add((node.lineno, "definition " + node.name))
                elif isinstance(node, ast.Name) and isinstance(node.ctx, ast.Store):
                    entries.add((node.lineno, "variable " + node.id))
                elif isinstance(node, ast.arg):
                    entries.add((node.lineno, "parameter " + node.arg))
        else:
            for number, line in enumerate(content.splitlines(), 1):
                patterns = (
                    r"\b(?:const|let|function|class|interface|type)\s+([\w]+)",
                    r"^\s*(?:private\s+)?([\w]+)\s*[?:=]",
                    r'\bid="([\w-]+)"',
                    r"CREATE (?:TABLE|TRIGGER) IF NOT EXISTS (\w+)",
                )
                for pattern in patterns:
                    for name in re.findall(pattern, line):
                        entries.add((number, name))
                if path.suffix == ".css" and "{" in line:
                    entries.add((number, line.split("{")[0].strip()))
        code.extend(
            [
                f"## {relative}",
                "",
                "| Line | Definition / variable / structural identifier |",
                "| --- | --- |",
            ]
        )
        code.extend(f"| {line} | `{name}` |" for line, name in sorted(entries))
        code.append("")
    catalog.extend(
        [
            "- `docs/CODE_INDEX.md` — Generated exact-line source inventory.",
            "- `docs/FILE_CATALOG.md` — This generated complete file index.",
            "",
        ]
    )
    return "\n".join(code), "\n".join(catalog)


def main() -> int:
    """Write generated documentation only on explicit --write; otherwise fail on drift."""
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    for name, content in zip(("CODE_INDEX.md", "FILE_CATALOG.md"), inventory(), strict=True):
        path = ROOT / "docs" / name
        if args.write:
            path.parent.mkdir(exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
        elif not path.is_file() or path.read_text(encoding="utf-8") != content:
            raise SystemExit(f"Stale {path.name}: run python tools/verify_repo.py --write")
    print("Code headers, definition contracts and exact-line/file indexes verified")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
